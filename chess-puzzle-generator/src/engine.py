def evaluate(board: chess.Board) -> int:
    """Score the position. Positive = good for white, negative = good for black."""
    if board.is_checkmate():
        return -20000 if board.turn == chess.WHITE else 20000
    if board.is_stalemate() or board.is_insufficient_material():
        return 0
    score = 0
    for square in chess.SQUARES:
        piece = board.piece_at(square)
        if piece is None:
            continue
        value = PIECE_VALUES[piece.piece_type]
        table = TABLES[piece.piece_type]
        pst_bonus = table[square] if piece.color == chess.WHITE else table[chess.square_mirror(square)]
        score += (value + pst_bonus) if piece.color == chess.WHITE else -(value + pst_bonus)
    return score


def order_moves(board: chess.Board) -> list:
    """Sort moves: captures (MVV-LVA) > promotions > checks > quiet moves."""
    def priority(move):
        p = 0
        if board.is_capture(move):
            victim = board.piece_at(move.to_square)
            attacker = board.piece_at(move.from_square)
            if victim and attacker:
                p += 10 * PIECE_VALUES[victim.piece_type] - PIECE_VALUES[attacker.piece_type]
        if move.promotion:
            p += PIECE_VALUES[move.promotion]
        if board.gives_check(move):
            p += 50
        return p
    return sorted(board.legal_moves, key=priority, reverse=True)


def minimax(board: chess.Board, depth: int, alpha: int, beta: int, maximising: bool) -> int:
    """Minimax with alpha-beta pruning."""
    if depth == 0 or board.is_game_over():
        return evaluate(board)
    if maximising:
        best = -float('inf')
        for move in order_moves(board):
            board.push(move)
            best = max(best, minimax(board, depth - 1, alpha, beta, False))
            board.pop()
            alpha = max(alpha, best)
            if beta <= alpha:
                break
        return best
    else:
        best = float('inf')
        for move in order_moves(board):
            board.push(move)
            best = min(best, minimax(board, depth - 1, alpha, beta, True))
            board.pop()
            beta = min(beta, best)
            if beta <= alpha:
                break
        return best


def best_move(board: chess.Board, depth: int = 3) -> Optional[chess.Move]:
    """Find the best move for the current player."""
    if board.is_game_over():
        return None
    best = None
    best_val = -float('inf') if board.turn == chess.WHITE else float('inf')
    for move in order_moves(board):
        board.push(move)
        val = minimax(board, depth - 1, -float('inf'), float('inf'),
                      board.turn == chess.WHITE)
        board.pop()
        if board.turn == chess.WHITE:
            if val > best_val:
                best_val, best = val, move
        else:
            if val < best_val:
                best_val, best = val, move
    return best
